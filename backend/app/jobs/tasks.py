@shared_task(bind=True)
def export_all_bookings_csv(self):
    """
    Admin-triggered async CSV export of all bookings.
    """
    from ..models import Booking
    bookings = Booking.query.order_by(Booking.created_at.desc()).all()

    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow([
        "Booking ID", "Trekker Name", "Trek Name", "Location",
        "Start Date", "End Date", "Booking Date",
        "Status", "Amount Paid", "Payment Method"
    ])

    for b in bookings:
        trek = b.trek
        trekker = b.user
        writer.writerow([
            b.id,
            trekker.full_name if trekker else "N/A",
            trek.name if trek else "N/A",
            trek.location if trek else "N/A",
            trek.start_date.isoformat() if trek and trek.start_date else "N/A",
            trek.end_date.isoformat() if trek and trek.end_date else "N/A",
            b.booking_date.strftime("%Y-%m-%d") if b.booking_date else "N/A",
            b.status,
            f"₹{b.amount_paid}" if b.amount_paid else "N/A",
            b.payment_method or "N/A",
        ])

    csv_content = output.getvalue()

    import os
    export_dir = "exports"
    os.makedirs(export_dir, exist_ok=True)
    filename = f"{export_dir}/all_bookings_export_{datetime.now().strftime('%Y%m%d%H%M%S')}.csv"
    with open(filename, "w", encoding="utf-8") as f:
        f.write(csv_content)

    # Send email notification to admin
    _send_email(
        to="admin@jatayu.in",
        subject="Jatayu | Admin Export of Bookings Ready",
        body=f"Namaste Admin! The CSV export of all bookings is ready and saved as {filename}."
    )

    return {"status": "done", "file": filename}

